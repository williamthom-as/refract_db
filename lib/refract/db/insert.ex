defmodule Refract.DB.Insert do
  @moduledoc false

  @type target :: module() | {String.t(), module()}

  @type error ::
          {:unknown_column | :cast_failed,
           %{line: pos_integer(), column: String.t(), inserted: non_neg_integer()}}

  @spec run(Enumerable.t(), module(), target(), keyword()) ::
          {:ok, non_neg_integer()} | {:error, error()}

  def run(rows, repo, target, opts) do
    schema = schema(target)
    size = opts |> Keyword.fetch!(:chunk) |> chunk(repo, schema)
    insert_all = Keyword.fetch!(opts, :insert_all)
    load = fn -> chunks(rows, repo, target, fields(schema), size, insert_all) end

    opts
    |> Keyword.fetch!(:transaction)
    |> commit(repo, load, Keyword.fetch!(opts, :timeout))
  end

  defp commit(true, repo, load, timeout) do
    with {:error, {reason, detail}} <- repo.transact(load, timeout: timeout),
         do: {:error, {reason, %{detail | inserted: 0}}}
  end

  defp commit(false, _repo, load, _timeout), do: load.()

  defp chunks(rows, repo, target, fields, size, insert_all) do
    rows
    |> Stream.with_index(1)
    |> Stream.chunk_every(size)
    |> Enum.reduce_while({:ok, 0}, fn lines, {:ok, count} ->
      lines
      |> entries(fields)
      |> inserted(repo, target, insert_all, count)
    end)
  end

  defp inserted({:ok, entries}, repo, target, insert_all, count) do
    {inserted, _returned} = repo.insert_all(target, autogenerated(entries, target), insert_all)

    {:cont, {:ok, count + inserted}}
  end

  defp inserted({:error, {reason, detail}}, _repo, _target, _insert_all, count),
    do: {:halt, {:error, {reason, Map.put(detail, :inserted, count)}}}

  defp entries(lines, fields) do
    lines
    |> Enum.reduce_while({:ok, []}, fn line, {:ok, entries} ->
      line |> entry(fields) |> collect(entries)
    end)
    |> reversed()
  end

  defp collect({:ok, entry}, entries), do: {:cont, {:ok, [entry | entries]}}
  defp collect(error, _entries), do: {:halt, error}

  defp reversed({:ok, entries}), do: {:ok, Enum.reverse(entries)}
  defp reversed(error), do: error

  defp entry({row, line}, fields) do
    Enum.reduce_while(row, {:ok, %{}}, fn {column, value}, {:ok, entry} ->
      fields
      |> field_value(column, value)
      |> put(entry, line, column)
    end)
  end

  defp put({:ok, field, value}, entry, _line, _column),
    do: {:cont, {:ok, Map.put(entry, field, value)}}

  defp put({:error, reason}, _entry, line, column),
    do: {:halt, {:error, {reason, %{line: line, column: column}}}}

  defp field_value(fields, column, value) do
    with {:ok, {field, type}} <- fetch_field(fields, column),
         {:ok, cast} <- cast(type, value),
         do: {:ok, field, cast}
  end

  defp fetch_field(fields, column) do
    with :error <- Map.fetch(fields, column), do: {:error, :unknown_column}
  end

  defp cast(type, ""), do: cast(type, nil)
  defp cast(type, value) when is_binary(value), do: type |> json?() |> cast_text(type, value)
  defp cast(type, value), do: type |> Ecto.Type.cast(value) |> cast_result()

  defp cast_text(true, type, value), do: value |> JSON.decode() |> cast_json(type)
  defp cast_text(false, type, value), do: type |> Ecto.Type.cast(value) |> cast_result()

  defp cast_json({:ok, decoded}, type), do: type |> Ecto.Type.cast(decoded) |> cast_result()
  defp cast_json({:error, _reason}, _type), do: {:error, :cast_failed}

  defp json?(:map), do: true
  defp json?({:map, _type}), do: true
  defp json?({:array, _type}), do: true
  defp json?(_type), do: false

  defp cast_result({:ok, value}), do: {:ok, value}
  defp cast_result(_error), do: {:error, :cast_failed}

  defp autogenerated(entries, target) do
    generated =
      target
      |> schema()
      |> then(& &1.__schema__(:autogenerate))
      |> Enum.flat_map(fn {fields, {module, function, args}} ->
        value = apply(module, function, args)
        Enum.map(fields, &{&1, value})
      end)
      |> Map.new()

    Enum.map(entries, &Map.merge(generated, &1, fn _field, value, given -> given || value end))
  end

  defp fields(schema) do
    names = schema.__schema__(:fields)
    by_source = Map.new(names, &{Atom.to_string(schema.__schema__(:field_source, &1)), &1})
    by_name = Map.new(names, &{Atom.to_string(&1), &1})

    by_source
    |> Map.merge(by_name)
    |> Map.new(fn {column, field} -> {column, {field, schema.__schema__(:type, field)}} end)
  end

  defp schema({_table, schema}), do: schema
  defp schema(schema), do: schema

  defp chunk(nil, repo, schema),
    do: repo.__adapter__() |> max_params() |> div(length(schema.__schema__(:fields)))

  defp chunk(size, _repo, _schema), do: size

  defp max_params(Ecto.Adapters.Postgres), do: 65_535
  defp max_params(Ecto.Adapters.MyXQL), do: 65_535
  defp max_params(Ecto.Adapters.SQLite3), do: 32_766

  defp max_params(adapter) do
    raise ArgumentError, "no bind parameter limit known for #{inspect(adapter)}, give chunk:"
  end
end
